export function activityIcon(name: string, label?: string) {
  const icon = createElement(icons[name as keyof typeof icons] ?? Gift, {
    width: 28,
    height: 28,
    'stroke-width': 1.8,
  });
  icon.classList.add('ww-question-icon');
  if (label) {
    icon.setAttribute('role', 'img');
    icon.setAttribute('aria-label', label);
  } else icon.setAttribute('aria-hidden', 'true');
  icon.setAttribute('focusable', 'false');
  return icon;
}

/** Use meaningful local icons for authored event/object labels; arbitrary labels stay text. */
export function pieceIcon(label: string) {
  const name = label.toLowerCase();
  const aliases: [RegExp, string][] = [
    [/wake|morning|sunrise/, 'sunrise'],
    [/breakfast|lunch|dinner|eat|serve|food/, 'utensils'],
    [/mix|bake/, 'cook'],
    [/socks|shoes|walk/, 'walk'],
    [/water/, 'water'],
    [/wash|brush/, 'hand'],
    [/leave|home|school/, 'door'],
    [/bed|sleep/, 'bed'],
    [/plant|sprout|seed/, 'sprout'],
    [/flower/, 'flower'],
    [/apple/, 'apple'],
    [/berry/, 'berry'],
    [/leaf/, 'leaf'],
    [/triangle/, 'triangle'],
    [/square/, 'square'],
    [/circle/, 'circle'],
  ];
  return activityIcon(aliases.find(([pattern]) => pattern.test(name))?.[1] ?? 'gift');
}
