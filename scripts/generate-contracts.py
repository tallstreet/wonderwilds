#!/usr/bin/env python3
"""Generate serde models and TypeScript interfaces from the shared bounded schema."""
import json, pathlib, re, sys, subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
schema=json.loads((ROOT/'contracts/schemas/v1.json').read_text())
D=schema['$defs']
def snake(s): return re.sub(r'(?<!^)(?=[A-Z])','_',s).lower()
def ts(s):
 if '$ref' in s:return s['$ref'].split('/')[-1]
 if 'const' in s:return json.dumps(s['const'])
 if 'enum' in s:return ' | '.join(json.dumps(x) for x in s['enum'])
 if 'oneOf' in s:return ' | '.join(ts(x) for x in s['oneOf'])
 t=s.get('type')
 if isinstance(t,list):return ' | '.join('null' if x=='null' else ts({**s,'type':x}) for x in t)
 if t=='object':
  if 'properties' not in s:return 'Record<string, '+ts(s['additionalProperties'])+'>'
  return '{ '+ '; '.join(k+('' if k in s['required'] else '?')+': '+ts(v) for k,v in s['properties'].items())+' }'
 if t=='array':return '('+ts(s['items'])+')[]'
 return {'string':'string','integer':'number','boolean':'boolean','null':'null'}[t]
extra={}
def rust(s,name):
 if '$ref' in s:return s['$ref'].split('/')[-1]
 if isinstance(s.get('type'),list):return 'Option<'+rust({**s,'type':next(x for x in s['type'] if x!='null')},name)+'>'
 if 'oneOf' in s or s.get('type')=='object' and 'properties' in s or 'enum' in s or 'const' in s:
  extra.setdefault(name,s); return name
 if s.get('type')=='array':return 'Vec<'+rust(s['items'],name+'Item')+'>'
 if s.get('type')=='object':return 'std::collections::BTreeMap<String, '+rust(s['additionalProperties'],name+'Value')+'>'
 return {'string':'String','integer':'u64','boolean':'bool'}[s['type']]
lines=['// Generated by scripts/generate-contracts.py; do not edit.','use serde::{Deserialize, Serialize};']
queue=list(D.items());done=set()
while queue:
 name,s=queue.pop(0)
 if name in done:continue
 done.add(name)
 lines+=['#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]']
 if 'oneOf' in s:
  lines+=['#[serde(untagged)]',f'pub enum {name} {{']
  for i,x in enumerate(s['oneOf']):lines+=[f'    Variant{i+1}({rust(x,name+"Variant"+str(i+1))}),']
 elif 'enum' in s or 'const' in s:
  lines+=[f'pub enum {name} {{']
  for i,x in enumerate(s.get('enum',[s.get('const')])):
   variant='V'+re.sub(r'[^A-Za-z0-9]','',x) if x[0].isdigit() else ''.join(p.title() for p in re.split(r'[_-]',x))
   lines += [f'    #[serde(rename = {json.dumps(x)})]',f'    {variant},']
 elif s.get('type')=='object':
  lines+=['#[serde(rename_all = "camelCase", deny_unknown_fields)]',f'pub struct {name} {{']
  for k,v in s['properties'].items():
   ty=rust(v,name+k[0].upper()+k[1:])
   if k not in s['required']:ty='Option<'+ty+'>';lines+=['    #[serde(default, skip_serializing_if = "Option::is_none")]']
   lines += [f'    pub {('r#' if snake(k) in ['type','ref','match','self'] else '')+snake(k)}: {ty},']
 else:raise ValueError(name)
 lines+=['}','']
 queue.extend((k,v) for k,v in extra.items() if k not in done)
outputs={ROOT/'contracts/generated/contracts.ts':'// Generated by scripts/generate-contracts.py; do not edit.\n'+''.join('export type '+k+' = '+ts(v)+';\n' for k,v in D.items()),ROOT/'contracts/src/models.rs':'\n'.join(lines)}
outputs[ROOT/'contracts/src/models.rs']=subprocess.run(['rustfmt','--edition','2024'],input=outputs[ROOT/'contracts/src/models.rs'],text=True,capture_output=True,check=True).stdout
check='--check' in sys.argv
for path,text in outputs.items():
 if check:
  if not path.exists() or path.read_text()!=text:raise SystemExit(f'Generated contract drift: {path.relative_to(ROOT)}')
 else:path.write_text(text)
print('Contract code generation '+('is current' if check else 'complete'))
