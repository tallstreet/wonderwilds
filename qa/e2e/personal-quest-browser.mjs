// Real browser + API + PostgreSQL. Run only through run-personal-quest-qa.mjs on a fresh QA database.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const origin = process.env.WW_DEMO_TEST_URL ?? 'http://127.0.0.1:5180';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => {
  if (response.url().includes('/api/') && response.status() >= 400)
    console.error('Browser API failure', response.status(), response.url());
});
try {
  await page.goto(origin);
  await page.waitForSelector('#game canvas');
  const bootstrap = await page.evaluate(async () => (await fetch('/__demo/bootstrap')).json());
  const headers = { 'X-Wonderwilds-Profile': bootstrap.profileId, 'X-CSRF-Token': bootstrap.csrf, Origin: origin };
  const snapshot = async () => {
    const response = await page.request.get(`${origin}/api/v1/game`, { headers });
    assert.equal(response.status(), 200);
    return response.json();
  };
  const post = body => page.request.post(`${origin}/api/v1/commands`, { headers, data: body });
  const command = async payload => {
    const state = await snapshot();
    const body = { schemaVersion: '1.0', commandId: crypto.randomUUID(), expectedRevision: state.revision, payload };
    const response = await post(body);
    assert.equal(response.status(), 200, `Command ${payload.type}: ${await response.text()}`);
    return { state: await response.json(), body };
  };
  const waitState = async predicate => {
    for (let i = 0; i < 100; i++) {
      const state = await snapshot();
      if (predicate(state)) return state;
      await page.waitForTimeout(100);
    }
    throw new Error('Timed out waiting for authoritative quest state');
  };
  const click = name => page.getByRole('button', { name, exact: true }).click();
  const keyboardActivate = async locator => { await locator.focus(); await page.keyboard.press('Enter'); };
  const journal = async () => {
    if (await page.locator('dialog[open]').count()) await click('Close dialog');
    await click('My journal');
    await page.getByRole('heading', { name: 'My adventure journal', exact: true }).waitFor();
  };
  const resume = async () => {
    await journal();
    await page.locator('[data-server-personal-resume], #server-personal-resume').first().click();
    await page.locator('.personal-quest-scene').waitFor();
  };
  const answerFor = encounter => {
    const p = encounter.parameters;
    if (encounter.templateId === 'missing_quantity') return { kind: 'quantity', value: p.total - p.given };
    if (encounter.templateId === 'equal_sharing') return { kind: 'groups', groups: Array(p.recipients).fill(p.total / p.recipients) };
    let ids;
    if (p.instructionId === 'count-next') ids = [p.objects.find(object => object.attribute === 'choice' && Number(object.label) === Number(p.objects[p.prefixLength - 1].label) + 1).id];
    else if (p.instructionId === 'pattern-next') ids = [p.objects.find(object => object.attribute === 'choice' && object.label === p.objects[p.prefixLength % p.unitLength].label).id];
    else if (p.instructionId === 'sort-round') ids = p.objects.filter(object => object.attribute === 'round').map(object => object.id);
    else if (p.promptId === 'sound-s') ids = [String(p.tiles.indexOf('s'))];
    else if (p.promptId === 'seed-order') ids = ['find_seed', 'plant_seed', 'water_seed'];
    else if (p.promptId === 'listen-direction') ids = [p.cards.find(card => card.text === 'Put the cup beside the tree.').id];
    else throw new Error(`Unsupported deterministic QA task ${JSON.stringify(p)}`);
    return { kind: 'choices', choiceIds: ids };
  };
  const complete = async beatId => {
    const started = await command({ type: 'start_encounter', beatId });
    const encounter = started.state.pendingEncounters[0];
    const finished = await command({ type: 'attempt', encounterId: encounter.id, answer: answerFor(encounter) });
    assert.equal(finished.state.pendingEncounters.length, 0, `${beatId} completed through real assessment`);
    return finished.state;
  };
  const quest = JSON.parse(await readFile(new URL('../../content/quests/pip-lantern-trail.v1.json', import.meta.url)));
  const catalog = JSON.parse(await readFile(new URL('../../content/quests/catalog.v1.json', import.meta.url)));
  const rewardId = catalog.quests.find(item => item.questId === quest.questId).rewardItemId;
  const entry = quest.nodes.find(node => node.id === quest.entryNodeId);
  const firstChoice = entry.choices[0], secondChoice = entry.choices[1];
  const quantity = state => state.inventory.find(item => item.itemId === rewardId)?.quantity ?? 0;
  assert.equal((await snapshot()).revision, 0, 'A fresh disposable QA database is required');
  const story = JSON.parse(await readFile(new URL('../../content/story/adventure.v1.json', import.meta.url)));
  for (const beat of story.beats.filter(beat => beat.chapterId === 'meadow')) await complete(beat.id);
  await complete('befriend-pip');
  const locked = await snapshot();
  assert.equal(locked.personalQuestOffers.find(offer => offer.questId === quest.questId).available, false);
  const lockedResponse = await post({ schemaVersion: '1.0', commandId: crypto.randomUUID(), expectedRevision: locked.revision, payload: { type: 'start_personal_quest', questId: quest.questId } });
  assert.ok([400, 403, 409].includes(lockedResponse.status()), 'Server rejects starting a level-locked episode');
  assert.equal((await snapshot()).revision, locked.revision);
  for (let i = 1; i <= 3; i++) await complete(`training-pip-${i}`);
  const unlocked = await snapshot();
  assert.equal(unlocked.characterProgression.find(item => item.creatureId === 'pip').level, 4);
  assert.equal(unlocked.personalQuestOffers.find(offer => offer.questId === quest.questId).available, true);
  console.log('PASS: real assessed recruitment/training and authoritative level-four quest unlock');

  await page.reload();
  await page.waitForSelector('#game canvas');
  await journal();
  await keyboardActivate(page.locator(`[data-server-personal-quest="${quest.questId}"]`).first());
  await page.locator(`[data-personal-node="${entry.id}"]`).waitFor();
  const initial = await snapshot(), episodeId = initial.personalQuest.episodeId;
  const beforeBadChoice = initial.revision;
  const invalidChoice = await post({ schemaVersion: '1.0', commandId: crypto.randomUUID(), expectedRevision: initial.revision, payload: { type: 'choose_personal_path', choiceId: 'not-a-real-choice' } });
  assert.ok([400, 403, 404, 409].includes(invalidChoice.status()));
  assert.equal((await snapshot()).revision, beforeBadChoice);
  const choiceRequest = page.waitForRequest(request => request.url().endsWith('/api/v1/commands') && request.method() === 'POST' && request.postDataJSON().payload.type === 'choose_personal_path');
  await keyboardActivate(page.locator(`[data-server-personal-choice="${firstChoice.id}"]`));
  const choiceBody = (await choiceRequest).postDataJSON();
  await page.locator(`[data-personal-node="${firstChoice.nextNodeId}"]`).waitFor();
  const branched = await snapshot();
  assert.equal(branched.personalQuest.node.id, firstChoice.nextNodeId);
  assert.deepEqual(branched.learnerSummaries, initial.learnerSummaries, 'Narrative choice is not a learning answer');
  await page.reload();
  await page.waitForSelector('#game canvas');
  await resume();
  assert.equal((await snapshot()).personalQuest.node.id, firstChoice.nextNodeId);
  assert.equal((await snapshot()).personalQuest.episodeId, episodeId);
  assert.equal((await post(choiceBody)).status(), 200);
  assert.equal((await snapshot()).revision, branched.revision, 'Exact old choice retry does not advance again');
  console.log('PASS: keyboard branching, invalid-choice rejection, persisted path and exact choice retry');

  await page.locator('#server-personal-activity').click();
  await page.locator('.ww-activity').waitFor();
  const issued = (await snapshot()).pendingEncounters[0];
  assert.equal(issued.personalQuest.questId, quest.questId);
  assert.equal(issued.personalQuest.nodeId, firstChoice.nextNodeId);
  assert.equal(issued.personalQuest.episodeId, episodeId);
  assert.equal(issued.templateId, 'missing_quantity');
  await click('Check my answer');
  await page.getByText(/Not quite yet/).waitFor();
  assert.equal((await snapshot()).personalQuest.node.id, firstChoice.nextNodeId);
  assert.equal(quantity(await snapshot()), 0);
  await click('Show a hint');
  await page.getByText(/This help is recorded as support/).waitFor();
  await page.reload();
  await page.waitForSelector('#game canvas');
  await page.locator('#missions').click();
  await click('Continue your activity');
  await page.locator('.ww-activity').waitFor();
  const resumed = (await snapshot()).pendingEncounters[0];
  assert.equal(resumed.id, issued.id);
  assert.equal(resumed.support.hintCount, 1);
  await click('Return to exploring');
  await waitState(state => state.pendingEncounters.length === 0);
  assert.equal((await snapshot()).personalQuest.node.id, firstChoice.nextNodeId);
  assert.equal(quantity(await snapshot()), 0);
  await resume();
  await page.locator('#server-personal-activity').click();
  await page.locator('.ww-activity').waitFor();
  await click('Show a hint');
  await page.getByText(/This help is recorded as support/).waitFor();
  const encounter = (await snapshot()).pendingEncounters[0];
  for (let i = 0; i < answerFor(encounter).value; i++) await click('Add one object');
  const attemptRequest = page.waitForRequest(request => request.url().endsWith('/api/v1/commands') && request.method() === 'POST' && request.postDataJSON().payload.type === 'attempt');
  await click('Check my answer');
  const attemptBody = (await attemptRequest).postDataJSON();
  const activityNode = quest.nodes.find(node => node.id === firstChoice.nextNodeId);
  const reflected = await waitState(state => state.personalQuest?.node.id === activityNode.nextNodeId && state.pendingEncounters.length === 0);
  assert.equal(reflected.personalQuest.episodeId, episodeId);
  assert.equal((await post(attemptBody)).status(), 200);
  assert.equal((await snapshot()).revision, reflected.revision);
  await resume();
  const reflection = quest.nodes.find(node => node.id === activityNode.nextNodeId);
  const handoffChoice = reflection.choices[0];
  const handoffRequest = page.waitForRequest(request => request.url().endsWith('/api/v1/commands') && request.method() === 'POST' && request.postDataJSON().payload.type === 'choose_personal_path');
  await page.locator(`[data-server-personal-choice="${handoffChoice.id}"]`).click();
  const handoffBody = (await handoffRequest).postDataJSON();
  await page.getByRole('heading', { name: 'What shall we explore next?', exact: true }).waitFor();
  const handoff = await snapshot();
  assert.equal(handoff.personalQuest.node.type, 'handoff');
  assert.equal(quantity(handoff), 1);
  assert.equal((await post(handoffBody)).status(), 200);
  assert.equal((await snapshot()).revision, handoff.revision);
  assert.equal(quantity(await snapshot()), 1);
  assert.ok(await page.locator(`[data-server-personal-quest="${quest.questId}"]`).isVisible());
  console.log('PASS: bound activity, wrong answer, support/reload, abandonment/resume, reflection and ongoing handoff');

  // Continue the selected hook into a genuinely related authored episode.
  const followupId = 'pip-star-pebble';
  assert.equal(handoff.personalQuestOffers[0].questId, followupId);
  const originalThread=handoff.narrativeMemory.threads.find(thread=>thread.tag==='night-sky' && thread.status==='open');
  assert.equal(originalThread.sourceChoiceId, handoffChoice.id);
  await page.locator(`[data-server-personal-quest="${followupId}"]`).click();
  await page.locator('.quest-acknowledgement').waitFor();
  const acknowledgement=await page.locator('.quest-acknowledgement').textContent();
  assert.match(acknowledgement,/star-shaped pebble/);
  await page.reload(); await page.waitForSelector('#game canvas'); await resume();
  assert.equal(await page.locator('.quest-acknowledgement').textContent(),acknowledgement);
  assert.equal((await snapshot()).narrativeMemory.threads.find(thread=>thread.id===originalThread.id).status,'open');
  await page.locator('[data-server-personal-choice="near"]').click();
  await page.locator('#server-personal-activity').click(); await page.locator('.ww-activity').waitFor();
  const followupActivity=(await snapshot()).pendingEncounters[0];
  for(let i=0;i<answerFor(followupActivity).value;i++) await click('Add one object');
  await click('Check my answer');
  await page.locator('[data-server-personal-choice="leaves"]').waitFor();
  await page.locator('[data-server-personal-choice="leaves"]').click();
  await page.getByRole('heading',{name:'What shall we explore next?',exact:true}).waitFor();
  const continued=await snapshot();
  assert.equal(continued.narrativeMemory.threads.find(thread=>thread.id===originalThread.id).status,'resolved');
  assert.equal(continued.personalQuestOffers[0].questId,'pip-woodland-whispers');
  const woodland=continued.narrativeMemory.threads.find(thread=>thread.tag==='woodland-trails' && thread.status==='open');
  assert.equal(woodland.sourceQuestId,followupId);
  await page.locator('[data-server-personal-quest="pip-woodland-whispers"]').click();
  await page.locator('.quest-acknowledgement').waitFor();
  assert.match(await page.locator('.quest-acknowledgement').textContent(),/rustling leaves/);
  await page.reload(); await page.waitForSelector('#game canvas'); await resume();
  assert.equal((await snapshot()).personalQuest.questId,'pip-woodland-whispers');
  await page.locator('#server-personal-abandon').click();
  await waitState(state=>state.personalQuest===undefined);
  assert.equal((await snapshot()).narrativeMemory.threads.find(thread=>thread.id===woodland.id).status,'open');
  await page.locator('[data-server-quest-interest="night-sky"]').click();
  await waitState(state=>state.questInterests.includes('night-sky'));
  await page.reload(); await page.waitForSelector('#game canvas');
  await page.locator('#missions').click(); await page.locator('#server-personal-adventures').click();
  await page.locator('[data-server-quest-interest="night-sky"][aria-pressed="true"]').waitFor();
  assert.equal((await snapshot()).personalQuestOffers[0].questId,'pip-woodland-whispers','A real unresolved hook outranks a different preferred theme');
  console.log('PASS: source-linked night-sky follow-up, acknowledged choice/reload, two-hop woodland continuation, unresolved abandonment and persisted interests');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(`[data-server-personal-quest="${quest.questId}"]`).click();
  await page.locator(`[data-personal-node="${entry.id}"]`).waitFor();
  const revisit = await snapshot();
  assert.notEqual(revisit.personalQuest.episodeId, episodeId);
  await page.locator(`[data-server-personal-choice="${secondChoice.id}"]`).click();
  await page.locator(`[data-personal-node="${secondChoice.nextNodeId}"]`).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone quest layout does not overflow');
  await page.locator('#server-personal-activity').click();
  await page.locator('.ww-activity').waitFor();
  const replayActivity = (await snapshot()).pendingEncounters[0];
  await command({ type: 'attempt', encounterId: replayActivity.id, answer: answerFor(replayActivity) });
  const replayReflection = (await snapshot()).personalQuest.node;
  await command({ type: 'choose_personal_path', choiceId: replayReflection.choices.at(-1).id });
  const replayed = await snapshot();
  assert.equal(replayed.personalQuest.node.type, 'handoff');
  assert.equal(quantity(replayed), 1, 'Revisiting another branch cannot farm the one-time keepsake');
  await page.reload();
  await page.waitForSelector('#game canvas');
  await resume();
  await page.getByRole('heading', { name: 'What shall we explore next?', exact: true }).waitFor();
  assert.equal((await snapshot()).personalQuest.node.type, 'handoff');
  assert.ok(await page.locator(`[data-server-personal-quest="${quest.questId}"]`).isVisible(), 'Another episode remains available after handoff/reload');
  await page.locator(`[data-server-personal-quest="${quest.questId}"]`).click();
  await page.locator(`[data-personal-node="${entry.id}"]`).waitFor();
  await page.locator('#server-personal-abandon').click();
  await waitState(state => state.personalQuest === undefined);
  assert.equal(quantity(await snapshot()), 1);
  assert.ok((await snapshot()).personalQuestOffers.some(offer => offer.available), 'Leaving an episode leaves another adventure available');
  assert.deepEqual(errors, []);
  console.log('PASS: mobile alternate branch, persisted handoff, narrative abandonment and repeatable adventures without duplicate rewards');
} catch (error) {
  console.error('Browser errors:', errors);
  console.error('Current dialog:', await page.locator('#dialog').innerText().catch(() => 'unavailable'));
  await page.screenshot({ path: '/tmp/wonderwilds-personal-quest-failure.png', fullPage: true }).catch(() => {});
  throw error;
} finally { await browser.close(); }
