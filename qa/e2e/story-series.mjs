// Three connected authored missions through actual Phaser interactions and a disposable API.
// WW_QA_BROWSER_TEST=qa/e2e/story-series.mjs node qa/e2e/run-training-qa.mjs
import assert from 'node:assert/strict';
import { finishInlineStep } from './inline-step.mjs';
import { chromium } from 'playwright';
const origin = process.env.WW_DEMO_TEST_URL ?? 'http://127.0.0.1:5180';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/?story=1`);
  await page.locator('#game canvas').waitFor();
  const bootstrap = await (await page.request.get(`${origin}/__demo/bootstrap`)).json();
  const get = async path => {
    const response = await page.request.get(`${origin}${path}`, { headers: { 'X-Wonderwilds-Profile': bootstrap.profileId } });
    assert.equal(response.status(), 200); return response.json();
  };
  const snapshot = () => get('/api/v1/story');
  const originalGame = await get('/api/v1/game');
  assert.equal((await snapshot()).revision, 0, 'Use a new disposable QA database');
  const close = async () => { if (await page.locator('dialog[open]').count()) await page.getByRole('button', { name: 'Close dialog', exact: true }).click(); };
  const ready = async () => {
    const state = await snapshot();
    await page.waitForFunction(revision => document.querySelector('#game')?.dataset.storyRevision === String(revision), state.revision);
    await page.waitForFunction(() => document.querySelector('#game')?.dataset.storyCrossing === 'false');
    return state;
  };
  const visit = async id => {
    await close(); await page.locator('#missions').click();
    await page.locator(`[data-story-visit="${id}"]`).click();
    await page.locator('dialog[open] [data-story-action], dialog[open] [data-story-continue]').first().waitFor({ timeout: 20000 });
    const marker = JSON.parse(await page.locator('#game').getAttribute('data-story-markers')).find(marker => marker.id === id);
    const point = await page.locator('#game').evaluate(node => ({ x: Number(node.dataset.storyPlayerX), y: Number(node.dataset.storyPlayerY) }));
    assert.ok(Math.hypot(point.x - marker.x, point.y - marker.y) < 110, `${id} requires actual approach`);
  };
  const choose = async type => {
    const revision = (await snapshot()).revision;
    await page.locator(`[data-story-action="${type}"]`).click();
    await finishInlineStep(page, type);
    await page.waitForFunction(previous => Number(document.querySelector('#game')?.dataset.storyRevision) > previous, revision, { timeout: 20000 });
    return ready();
  };
  const act = async (marker, type) => {
    if (type === 'cancel_mission') { await close(); await page.locator('#missions').click(); }
    else await visit(marker);
    return choose(type);
  };
  const travel = destination => act(`route:${destination}`, 'travel');
  const reload = async () => { await close(); await page.reload(); await page.locator('#game canvas').waitFor(); return ready(); };
  const mission = async (id, status) => {
    const state = await ready();
    assert.equal(state.sceneInput.mission.missionId, id);
    assert.equal(state.sceneInput.mission.status, status);
    return state;
  };
  const accompany = async destination => {
    await visit('npc:pip');
    const revision = (await snapshot()).revision;
    await page.locator('[data-story-action="accompany"]').click();
    await page.waitForFunction(() => {
      const surface = document.querySelector('#game');
      if (surface?.dataset.storyCrossing !== 'true') return false;
      return JSON.parse(surface.dataset.storyFollowers ?? '[]').some(follower => follower.sprite === 'pip');
    });
    const followers = JSON.parse(await page.locator('#game').getAttribute('data-story-followers'));
    assert.equal(followers.length, 1);
    assert.ok(!JSON.parse(await page.locator('#game').getAttribute('data-story-markers')).some(marker => marker.id === 'npc:pip'));
    const state = await ready();
    assert.ok(state.revision > revision);
    assert.equal(state.locationId, destination);
    const x = Number(await page.locator('#game').getAttribute('data-story-player-x'));
    assert.ok(destination === 'far_bank' ? x >= 780 : x <= 600, 'Shared crossing reaches its confirmed bank');
  };
  await act('npc:pip', 'accept_mission');
  await act('resource:fallen_wood', 'collect');
  await travel('workshop');
  await visit('npc:woodcutter');
  const beforeAck = (await snapshot()).revision;
  await page.locator('[data-story-continue]').click();
  await page.waitForFunction(revision => Number(document.querySelector('#game')?.dataset.storyRevision) > revision, beforeAck);
  await act('npc:woodcutter', 'exchange');
  await travel('bridge_bank');
  await act('object:bridge', 'assemble');
  await accompany('far_bank');
  const bridge = await mission('pips_bridge', 'completed');
  await reload();
  assert.equal((await snapshot()).sceneInput.mission.goal, bridge.sceneInput.mission.goal);
  await page.locator('#missions').click(); await page.locator('[data-story-next]').waitFor();
  await act('npc:pip', 'accept_mission');
  let picnic = await mission('pips_picnic', 'active');
  assert.ok(picnic.sceneInput.context.memory.recentMissions.length >= 1);
  await act('npc:pip', 'cancel_mission');
  await reload(); await mission('pips_picnic', 'abandoned');
  await act('npc:pip', 'accept_mission');
  await act('resource:berry_bush', 'collect');
  await travel('bridge_bank'); await travel('workshop');
  await act('npc:woodcutter', 'exchange');
  assert.deepEqual((await snapshot()).sceneInput.context.inventory, [{ itemId: 'picnic_basket', quantity: 1 }]);
  await travel('bridge_bank'); await act('object:picnic_table', 'assemble');
  assert.ok(JSON.parse(await page.locator('#game').getAttribute('data-story-visuals')).some(item => item.id === 'picnic_table'));
  assert.equal((await snapshot()).sceneInput.mission.status, 'active', 'A ready picnic still needs Pip');
  await travel('far_bank'); await accompany('bridge_bank');
  picnic = await mission('pips_picnic', 'completed');
  await reload();
  assert.equal((await snapshot()).sceneInput.mission.goal, picnic.sceneInput.mission.goal);
  await act('npc:pip', 'accept_mission');
  await mission('welcome_lights', 'active');
  await travel('far_bank'); await act('resource:glow_stones', 'collect');
  await travel('bridge_bank'); await travel('workshop');
  // Lose an actual committed pause response, reload, then replay its original body.
  await visit('npc:woodcutter');
  await page.locator('[data-story-action="exchange"]').click();
  await finishInlineStep(page, 'exchange');
  await page.locator('#missions').click();
  let originalBody;
  await page.route('**/api/v1/story/commands', async route => {
    originalBody = route.request().postData();
    const response = await route.fetch(); assert.equal(response.status(), 200);
    await route.abort('failed');
  }, { times: 1 });
  await page.locator('[data-story-action="cancel_mission"]').click();
  await page.locator('[data-story-retry]').waitFor();
  const committedRevision = (await snapshot()).revision;
  await reload(); await page.locator('#missions').click();
  assert.equal(await page.locator('[data-story-visit]:enabled').count(), 0);
  const retry = page.waitForRequest(request => request.url().endsWith('/story/commands'));
  await page.locator('[data-story-retry]').click();
  assert.equal((await retry).postData(), originalBody);
  await page.locator('dialog').waitFor({ state: 'hidden' });
  assert.equal((await ready()).revision, committedRevision);
  await page.locator('#missions').click();
  await page.locator('[data-story-action="accept_mission"]').click();
  await page.locator('dialog').waitFor({ state: 'hidden' });
  await ready();
  assert.deepEqual((await snapshot()).sceneInput.context.inventory, [{ itemId: 'lanterns', quantity: 3 }]);
  await travel('bridge_bank'); await act('object:near_lanterns', 'assemble');
  assert.deepEqual((await snapshot()).sceneInput.context.inventory, [{ itemId: 'lanterns', quantity: 1 }]);
  await travel('far_bank'); await act('object:far_lantern', 'assemble');
  const final = await mission('welcome_lights', 'completed');
  assert.deepEqual(final.sceneInput.context.inventory, []);
  assert.equal(final.sceneInput.context.memory.recentMissions.length, 3);
  assert.ok(!final.sceneInput.availableActions.some(item => item.action.type === 'accept_mission'));
  const visuals = JSON.parse(await page.locator('#game').getAttribute('data-story-visuals'));
  assert.equal(visuals.filter(item => item.kind === 'lantern').length, 3);
  assert.equal(visuals.filter(item => item.kind === 'picnic').length, 1);
  await page.screenshot({ path: '/tmp/wonderwilds-story-series-desktop.png', fullPage: true });
  await reload(); assert.equal((await snapshot()).revision, final.revision);
  assert.deepEqual(JSON.parse(await page.locator('#game').getAttribute('data-story-visuals')), visuals);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#missions').click();
  await page.locator('[data-story-history]').waitFor();
  assert.equal(await page.locator('[data-story-history] li').count(), 3);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '/tmp/wonderwilds-story-series-mobile.png', fullPage: true });
  await page.goto(`${origin}/story.html`);
  await page.locator('#game canvas').waitFor();
  await page.locator('#missions').click();
  await page.locator('[data-story-mission-status="completed"]').waitFor();
  await page.getByText(final.sceneInput.mission.goal, { exact: true }).waitFor();
  assert.ok((await page.locator('dialog').innerText()).includes(final.sceneInput.mission.narrative.payoff));
  assert.deepEqual(await get('/api/v1/game'), originalGame, 'Education/adventure state stays untouched');
  assert.deepEqual(errors, []);
  console.log('PASS: three Phaser stories, persistent world changes/history, explicit next acceptance, reverse Pip crossing, pause/reload, exact replay, mobile inspector, separate education');
} finally { await browser.close(); }
